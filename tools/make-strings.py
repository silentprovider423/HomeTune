root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
keys = set()
# iPhone-App (build/, von test.sh) und Mac-App (build/mac-dd/, von run-mac.sh/test-mac.sh)
for f in glob.glob(os.path.join(root, "build/Build/Intermediates.noindex/HomeTune.build/*/HomeTune.build/**/*.stringsdata"), recursive=True) + \
         glob.glob(os.path.join(root, "build/mac-dd/Build/Intermediates.noindex/HomeTune.build/*/HomeTuneMac.build/**/*.stringsdata"), recursive=True):
    for table in json.load(open(f)).get("tables", {}).values():
        keys.update(e["key"] for e in table)
keys.discard("")
missing = sorted(k for k in keys if k not in EN)
if not keys:
    sys.exit("Keine .stringsdata gefunden – erst bauen.")
strings = {}
for k in sorted(keys):
    en = EN.get(k, k)
    entry = {"localizations": {"en": {"stringUnit": {"state": "translated", "value": en}}}}
    if k in DE:
        entry["localizations"]["de"] = {"stringUnit": {"state": "translated", "value": DE[k]}}
    elif k.count("%") > 1:
        # Positionsangaben auch für Deutsch, damit die Reihenfolge eindeutig ist
        counter = iter(range(1, 10))
        de = re.sub(r"%(lld|@)", lambda m: f"%{next(counter)}${m.group(1)}", k)
        entry["localizations"]["de"] = {"stringUnit": {"state": "translated", "value": de}}
    strings[k] = entry
out = {"sourceLanguage": "de", "strings": strings, "version": "1.0"}
with open(os.path.join(root, "Resources/Localizable.xcstrings"), "w", encoding="utf-8") as fh:
    json.dump(out, fh, ensure_ascii=False, indent=2, sort_keys=True)
print(f"{len(strings)} Texte geschrieben.")
if missing:
    print("Ohne Übersetzung:", *missing, sep="\n  ")
